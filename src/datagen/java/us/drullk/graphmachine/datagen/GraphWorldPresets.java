package us.drullk.graphmachine.datagen;

import java.util.Map;
import net.minecraft.core.HolderGetter;
import net.minecraft.core.registries.Registries;
import net.minecraft.data.worldgen.BootstrapContext;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.biome.Biomes;
import net.minecraft.world.level.dimension.DimensionType;
import net.minecraft.world.level.dimension.LevelStem;
import net.minecraft.world.level.levelgen.presets.WorldPreset;
import us.drullk.graphmachine.worldgen.GraphChunkGenerator;
import us.drullk.graphmachine.worldgen.GraphDimensionTypes;
import us.drullk.graphmachine.worldgen.GraphPresets;

/**
 * Builds the {@code graphmachine:graph} world preset. Its only dimension is an overworld of the
 * {@code graphmachine:graph} dimension type, generated by {@link GraphChunkGenerator} in the plains biome.
 * The dimension type is what tells the client to draw the graph.
 *
 * <p>Written by Claude Code; conversation transcript: {@code llm/transcripts/transcript_2026-10-16_07-43_2aec7285-4ea5-4d89-ba3e-f516a9a7bde0.md}.
 * <p>Written by Claude Code; conversation transcript: {@code llm/transcripts/transcript_2026-10-16_23-43_3d80b42f-de61-4c60-b018-5e44e36d8860.md}.
 */
public final class GraphWorldPresets {
    private GraphWorldPresets() {
    }

    public static void bootstrap(BootstrapContext<WorldPreset> context) {
        HolderGetter<DimensionType> dimensionTypes = context.lookup(Registries.DIMENSION_TYPE);
        HolderGetter<Biome> biomes = context.lookup(Registries.BIOME);
        LevelStem overworld = new LevelStem(dimensionTypes.getOrThrow(GraphDimensionTypes.GRAPH), new GraphChunkGenerator(biomes.getOrThrow(Biomes.PLAINS)));
        context.register(GraphPresets.GRAPH, new WorldPreset(Map.of(LevelStem.OVERWORLD, overworld)));
    }
}
